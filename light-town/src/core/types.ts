import type { AccessorySlot, PartnerId, ThemeId } from '../config/shop';
import type { ActiveTask, P2Data, P2TaskResult } from './phase2/types';

export type { ActiveTask };

export type Mode = 'keys' | 'strip' | 'sign';

/**
 * How a level was started.
 * light: 继续点亮 (advances the current building) · learn: 继续学习 after all buildings ·
 * route: 学习路线 · replay: 重练已完成建筑 · free: 自由练习 · festival: 灯光节轮次
 */
export type Entry = 'light' | 'learn' | 'route' | 'replay' | 'free' | 'festival';

/** One accepted attempt in the bounded recent buffer: target key and whether it matched. */
export type RecentAttempt = [key: string, ok: 0 | 1];

export interface Settings {
  music: boolean;
  sfx: boolean;
  voice: boolean;
  musicVolume: number;
  sfxVolume: number;
  voiceVolume: number;
  masterMute: boolean;
  reduceMotion: boolean;
}

export interface CourseState {
  /** Highest opened course stage (1–12). */
  stage: number;
  /** Stage 12 passed: 全部按键课程已完成. */
  allComplete: boolean;
  /** New-key correct counts of the previous qualifying standard level; null when no level is pending. */
  lastQualifying: Record<string, number> | null;
  nextMode: 'keys' | 'strip';
  /** Highest stage whose new-key introduction has been shown. */
  introSeen: number;
}

export interface FestivalRound {
  id: string;
  done: [boolean, boolean, boolean];
}

export interface FestivalState {
  unlocked: boolean;
  round: FestivalRound | null;
  roundsCompleted: number;
}

export interface Session {
  id: string;
  startedAt: number;
  lastActivityAt: number;
  levelsCompleted: number;
  attempts: number;
  correct: number;
  effectiveMs: number;
  coins: number;
  buildingsAtStart: number[];
  remindersShown: number;
}

export interface LevelKeyCount {
  a: number;
  c: number;
}

export interface LevelState {
  id: string;
  seq: number;
  entry: Entry;
  mode: Mode;
  autoMode: boolean;
  courseStage: number;
  /** Comparison key for "same course" encouragement, e.g. "stage:3" or "custom:a,f,j". */
  courseLabel: string;
  keys: string[];
  /** Generated by the standard course algorithm (counts toward promotion if still the current stage). */
  standard: boolean;
  buildingTarget: number | null;
  replayBuilding: number | null;
  festival: { roundId: string; index: number } | null;
  seed: number;
  targets: string[];
  words: string[] | null;
  wordStarts: number[] | null;
  newKeyQuota: Record<string, number>;
  pos: number;
  attempts: number;
  correct: number;
  keyCounts: Record<string, LevelKeyCount>;
  wrongStreak: number;
  effectiveMs: number;
  createdAt: number;
  paused: boolean;
  activeSince: number | null;
  lastInputAt: number | null;
  accountedUntil: number | null;
  targetShownAt: number | null;
}

export interface KeyStat {
  attempts: number;
  correct: number;
  presented: number;
}

export interface DailyStat {
  attempts: number;
  correct: number;
  effectiveMs: number;
  levels: number;
}

export interface LevelSummary {
  id: string;
  at: number;
  entry: Entry;
  mode: Mode;
  course: string;
  attempts: number;
  correct: number;
  effectiveMs: number;
  coins: number;
}

export interface Stats {
  attempts: number;
  correct: number;
  effectiveMs: number;
  levelsCompleted: number;
  keys: Record<string, KeyStat>;
  mistypes: Record<string, Record<string, number>>;
  recent: RecentAttempt[];
  daily: Record<string, DailyStat>;
  levels: LevelSummary[];
}

export interface CoinBreakdown {
  base: number;
  accuracy: number;
  building: number;
  district: number;
  festival: number;
  total: number;
}

export interface LevelResult {
  levelId: string;
  at: number;
  entry: Entry;
  mode: Mode;
  courseStage: number;
  courseLabel: string;
  attempts: number;
  correct: number;
  effectiveMs: number;
  coins: CoinBreakdown;
  building: { index: number; before: number; after: number; completed: boolean } | null;
  replayBuilding: number | null;
  districtOpened: number | null;
  festivalUnlocked: boolean;
  festival: { index: number; roundComplete: boolean } | null;
  promotion: { promotedTo: number | null; allComplete: boolean; streak: number } | null;
  encouragement: string;
  restReminder: boolean;
  wordsCompleted: string[] | null;
}

export interface SaveData {
  schemaVersion: 2;
  revision: number;
  createdAt: number;
  updatedAt: number;
  partner: PartnerId | null;
  onboarded: boolean;
  settings: Settings;
  course: CourseState;
  buildings: number[];
  /** Index of the building being lit (0–11); 12 when all buildings are complete. */
  currentBuilding: number;
  coins: number;
  owned: string[];
  equipped: Record<AccessorySlot, string | null>;
  themesOwned: ThemeId[];
  theme: ThemeId;
  festival: FestivalState;
  session: Session | null;
  /** 两阶段共用的未完成任务槽（第一阶段关或第二阶段任务）。 */
  activeTask: ActiveTask | null;
  lastResult: LevelResult | null;
  /** 第二阶段最近一次任务结算结果（结果页显示一次；刷新不重结算）。 */
  lastTaskResult: P2TaskResult | null;
  stats: Stats;
  settled: string[];
  levelSeq: number;
  wordLevels: string[][];
  wordLevelsPlayed: number;
  seen: Record<string, boolean>;
  /** 第二阶段进度（路线、题单、复习、统计、首次奖励）。 */
  phase2: P2Data;
}

export interface SessionSummary {
  levelsCompleted: number;
  attempts: number;
  correct: number;
  effectiveMs: number;
  coins: number;
  buildingChanges: { index: number; from: number; to: number }[];
  partialLevel: { attempts: number; correct: number } | null;
}
